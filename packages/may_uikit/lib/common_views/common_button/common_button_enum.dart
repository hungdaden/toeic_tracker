/// Visual variants supported by the common button.
enum CommonButtonVariant {
  /// Filled primary button.
  primary,

  /// Filled secondary button.
  secondary,

  /// Text-only button without card background.
  textOnly,

  /// Outline button.
  outline,

  /// Filled critical action button.
  criticalPrimary,

  /// Outline critical action button.
  criticalOutline,

  /// Filled success button with optional subtitle.
  success,
}

/// Size presets supported by the common button.
enum CommonButtonSize {
  /// Large button preset.
  large,

  /// Medium button preset.
  medium,
}
